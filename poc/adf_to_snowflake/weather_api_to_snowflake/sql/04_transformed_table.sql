-- create a table to store the transformed weather data. This table will have columns for each of the fields we want to extract from the JSON response.
create or replace TABLE TRANSFORMED.WEATHER_DATA (
	AREA_NAME VARCHAR(16777216),
	COUNTRY VARCHAR(16777216),
	REGION VARCHAR(16777216),
	LATITUDE VARCHAR(16777216),
	LONGITUDE VARCHAR(16777216),
	POPULATION VARCHAR(16777216),
	TEMP_C NUMBER(38,0),
	TEMP_F NUMBER(38,0),
	FEELS_LIKE_C NUMBER(38,0),
	FEELS_LIKE_F NUMBER(38,0),
	HUMIDITY NUMBER(38,0),
	CLOUDCOVER NUMBER(38,0),
	PRESSURE NUMBER(38,0),
	UV_INDEX NUMBER(38,0),
	VISIBILITY NUMBER(38,0),
	WEATHER_CODE VARCHAR(16777216),
	WEATHER_DESC VARCHAR(16777216),
	OBSERVATION_TIME VARCHAR(16777216),
	WINDSPEED_KMPH NUMBER(38,0),
	WINDSPEED_MILES NUMBER(38,0),
	WIND_DIR_16POINT VARCHAR(16777216),
	WIND_DIR_DEGREE NUMBER(38,0),
	REQUEST_QUERY VARCHAR(16777216),
	REQUEST_TYPE VARCHAR(16777216),
	SUNRISE VARCHAR(16777216),
	SUNSET VARCHAR(16777216),
    INSERT_AT TIMESTAMP_NTZ 
);
