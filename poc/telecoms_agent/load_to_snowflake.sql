--Test query
--Provinces with the highest missed-call rate on hunt groups
SELECT cu.province,
       COUNT(*)                                                        AS inbound_hunt_group_calls,
       COUNT_IF(c.disposition = 'Missed')                              AS missed_calls,
       ROUND(100 * COUNT_IF(c.disposition = 'Missed') / COUNT(*), 1)   AS missed_rate_pct,
       ROUND(100 * COUNT_IF(c.disposition IN ('Missed','Abandoned')) / COUNT(*), 1) AS missed_or_abandoned_pct
FROM fact_call_detail c
JOIN dim_call_group g  ON g.call_group_id = c.call_group_id AND g.group_type = 'Hunt Group'
JOIN dim_customer  cu  ON cu.customer_id  = c.customer_id
WHERE c.direction = 'Inbound'
GROUP BY cu.province
ORDER BY missed_rate_pct DESC;