CREATE OR REPLACE TABLE DIM_PLAN (
  PLAN_ID STRING PRIMARY KEY, PLAN_NAME STRING, LIST_PRICE_CAD NUMBER(8,2), INTERNET_BUNDLE_PRICE_CAD NUMBER(8,2),
  DESK_PHONE_INCLUDED BOOLEAN, MOBILE_APP_INCLUDED BOOLEAN, TEAMS_INTEGRATION_INCLUDED BOOLEAN,
